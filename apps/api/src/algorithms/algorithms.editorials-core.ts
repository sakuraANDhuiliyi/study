import { coreReferencePrograms } from './algorithms.editorials-references';

const approach = (
  name: string,
  intuition: string,
  steps: string[],
  correctness: string,
  timeComplexity: string,
  spaceComplexity: string,
  tradeoff: string,
): AlgorithmEditorialApproach => ({
  name,
  intuition,
  steps,
  correctness,
  timeComplexity,
  spaceComplexity,
  tradeoff,
});
const walk = (input: string, result: string, rows: [string, string][]): AlgorithmEditorialWalkthrough => ({
  input,
  result,
  steps: rows.map(([state, explanation], index) => ({ step: index + 1, state, explanation })),
});
const entry = (
  problemId: string,
  content: Omit<AlgorithmEditorial, 'problemId' | 'referenceCode'>,
): AlgorithmEditorial => ({ problemId, ...content, referenceCode: coreReferencePrograms[problemId] });

